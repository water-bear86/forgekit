import { describe, expect, it } from "vitest";
import { buildLicenseMetadata } from "../../shared/licenseMetadata";

describe("buildLicenseMetadata", () => {
  it("includes marketplace fields, traits, seed, pricing, and loot boost", () => {
    const metadata = buildLicenseMetadata({
      name: "ForgeKit Genesis Pass #000001",
      description: "ForgeKit Genesis Pass generated by ForgeKit.",
      image: "https://storage.example/license.png",
      externalUrl: "https://forgekit.example/asset/1",
      attributes: [
        { trait_type: "eyes", value: "Eyeballs Made Of Galaxies" },
        { trait_type: "rarity_score", value: 1001 },
      ],
      properties: {
        wallet: "wallet",
        seed: "seed",
        offerId: "standard",
        traitPackId: "starter",
        loot: 42,
        lootBoost: 0.357,
        pricingSnapshot: { targetUsd: 2.5 },
      },
    });

    expect(metadata).toMatchObject({
      name: "ForgeKit Genesis Pass #000001",
      description: "ForgeKit Genesis Pass generated by ForgeKit.",
      image: "https://storage.example/license.png",
      external_url: "https://forgekit.example/asset/1",
      properties: {
        category: "image",
        files: [{ uri: "https://storage.example/license.png", type: "image/png" }],
        lootBoost: 0.357,
        pricingSnapshot: { targetUsd: 2.5 },
      },
    });
    expect(metadata.attributes).toHaveLength(2);
  });

  it("does not let caller properties override marketplace category or files", () => {
    const metadata = buildLicenseMetadata({
      name: "ForgeKit Genesis Pass #000001",
      description: "ForgeKit Genesis Pass generated by ForgeKit.",
      image: "https://storage.example/license.png",
      externalUrl: "https://forgekit.example/asset/1",
      attributes: [],
      properties: {
        category: "video",
        files: [{ uri: "https://storage.example/not-license.mp4", type: "video/mp4" }],
      },
    });

    expect(metadata.properties.category).toBe("image");
    expect(metadata.properties.files).toEqual([{ uri: "https://storage.example/license.png", type: "image/png" }]);
  });
});
