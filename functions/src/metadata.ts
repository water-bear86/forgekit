import {
  buildLicenseMetadata,
  type LicenseAttribute,
  type LicenseMetadata,
} from "../../shared/licenseMetadata.js";

export interface BuildLicenseMetadataRecordInput {
  licenseNumber: number;
  wallet: string;
  seed: string;
  image: string;
  externalUrl: string;
  projectName?: string;
  description?: string;
  offerId: string;
  traitPackId: string;
  loot: number;
  lootBoost: number;
  pricingSnapshot: Record<string, unknown>;
  traits: LicenseAttribute[];
}

export function buildLicenseMetadataRecord(input: BuildLicenseMetadataRecordInput): LicenseMetadata {
  if (!Number.isSafeInteger(input.licenseNumber) || input.licenseNumber <= 0) {
    throw new Error("licenseNumber must be a positive safe integer.");
  }

  const projectName = input.projectName?.trim() || "ForgeKit Genesis Pass";
  const name = `${projectName} #${input.licenseNumber.toString().padStart(6, "0")}`;

  return buildLicenseMetadata({
    name,
    description: input.description?.trim() || `${projectName} generated by ForgeKit.`,
    image: input.image,
    externalUrl: input.externalUrl,
    attributes: input.traits,
    properties: {
      wallet: input.wallet,
      seed: input.seed,
      offerId: input.offerId,
      traitPackId: input.traitPackId,
      loot: input.loot,
      lootBoost: input.lootBoost,
      pricingSnapshot: input.pricingSnapshot,
    },
  });
}

export interface BuildLicenseRecordInput {
  licenseId: string;
  wallet: string;
  ownerAtMint: string;
  assetAddress: string;
  imagePath: string;
  metadataPath: string;
  rarityScore: number;
  traits: LicenseAttribute[];
  loot: number;
  lootBoost: number;
  pricingSnapshot: Record<string, unknown>;
  nowIso: string;
}

export interface LicenseRecord {
  licenseId: string;
  wallet: string;
  ownerAtMint: string;
  assetAddress: string;
  imagePath: string;
  metadataPath: string;
  rarityScore: number;
  traits: LicenseAttribute[];
  loot: number;
  lootBoost: number;
  pricingSnapshot: Record<string, unknown>;
  createdAt: string;
  updatedAt: string;
}

export function buildLicenseRecord(input: BuildLicenseRecordInput): LicenseRecord {
  const licenseId = requireNonEmpty(input.licenseId, "licenseId");
  const wallet = requireNonEmpty(input.wallet, "wallet");
  const ownerAtMint = requireNonEmpty(input.ownerAtMint, "ownerAtMint");
  const assetAddress = requireNonEmpty(input.assetAddress, "assetAddress");
  const imagePath = requireNonEmpty(input.imagePath, "imagePath");
  const metadataPath = requireNonEmpty(input.metadataPath, "metadataPath");
  requireNonNegativeFinite(input.rarityScore, "rarityScore");
  requireNonNegativeInteger(input.loot, "loot");
  requireNonNegativeFinite(input.lootBoost, "lootBoost");
  requireNonEmpty(input.nowIso, "nowIso");

  return {
    licenseId,
    wallet,
    ownerAtMint,
    assetAddress,
    imagePath,
    metadataPath,
    rarityScore: input.rarityScore,
    traits: input.traits,
    loot: input.loot,
    lootBoost: input.lootBoost,
    pricingSnapshot: input.pricingSnapshot,
    createdAt: input.nowIso,
    updatedAt: input.nowIso,
  };
}

function requireNonEmpty(value: string, field: string): string {
  const trimmed = value.trim();
  if (!trimmed) throw new Error(`${field} is required`);
  return trimmed;
}

function requireNonNegativeFinite(value: number, field: string): void {
  if (!Number.isFinite(value) || value < 0) {
    throw new Error(`${field} must be non-negative`);
  }
}

function requireNonNegativeInteger(value: number, field: string): void {
  if (!Number.isSafeInteger(value) || value < 0) {
    throw new Error(`${field} must be a non-negative integer`);
  }
}
